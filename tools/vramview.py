def addr32(x, y, bp, bw, z=False):
    page = ((y >> 5) * bw + (x >> 6)) * 32
    t = bt32z if z else bt32
    blk = bp + page + t[(y >> 3) & 3][(x >> 3) & 7]
    return ((blk & 0x3FFF) << 6) + ct32[y & 7][x & 7]


def addr16(x, y, bp, bw):
    page = ((y >> 6) * bw + (x >> 6)) * 32
    blk = bp + page + bt16[(y >> 3) & 7][(x >> 4) & 3]
    return ((blk & 0x3FFF) << 7) + ct16[y & 7][x & 15]


def addr8(x, y, bp, bw):
    page = ((y >> 6) * (bw >> 1) + (x >> 7)) * 32
    blk = bp + page + bt8[(y >> 4) & 3][(x >> 4) & 7]
    return ((blk & 0x3FFF) << 8) + ct8[y & 15][x & 15]


def main():
    path, out, psm = sys.argv[1], sys.argv[2], sys.argv[3]
    bp, bw, w, h = int(sys.argv[4], 16), int(sys.argv[5]), int(sys.argv[6]), int(sys.argv[7])
    raw = open(path, 'rb').read()
    v32 = np.frombuffer(raw[:4 << 20], dtype=np.uint32)
    v16 = np.frombuffer(raw[:4 << 20], dtype=np.uint16)
    v8 = np.frombuffer(raw[:4 << 20], dtype=np.uint8)
    img = np.zeros((h, w, 4), dtype=np.uint8)
    clut = None
    if psm in ('t8', 't4'):
        cbp = int(sys.argv[8], 16)
        clut = []
        for i in range(256):
            x, y = i & 15, i >> 4
            j = (i & ~0x18) | ((i & 0x08) << 1) | ((i & 0x10) >> 1)
            clut.append((j, int(v32[addr32(x, y, cbp, 1)])))
        c = [0] * 256
        for j, val in clut:
            c[j] = val
        clut = c
    for y in range(h):
        for x in range(w):
            if psm in ('ct32', 'ct24', 'z32'):
                c = int(v32[addr32(x, y, bp, bw, psm == 'z32')])
            elif psm == 'ct16':
                p = int(v16[addr16(x, y, bp, bw)])
                c = ((p & 0x1F) << 3) | (((p >> 5) & 0x1F) << 11) | (((p >> 10) & 0x1F) << 19) | 0xFF000000
            elif psm == 't8':
                c = clut[int(v8[addr8(x, y, bp, bw)])]
            else:
                c = 0
            img[y, x] = [c & 0xFF, (c >> 8) & 0xFF, (c >> 16) & 0xFF, 255]
    Image.fromarray(img, 'RGBA').convert('RGB').save(out)
    print('saved', out, img[..., :3].min(), img[..., :3].max())


if __name__ == '__main__':
    main()
