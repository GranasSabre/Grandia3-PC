# Battle texts in GR3.MDT that the system text tables do not reach: the party's battle calls
# ("Cancel <3>!"), the tactical advice ("<5> works well against <3>") and the battle tutorial
# script. They are overwritten in place with German texts of exactly the same byte length (kind k
# in lang/<language>_sys.tsv: GR3 offset, length, FNV-1a 32 of the original, bytes as {hex}).
#   python btl_text.py extract <GR3.MDT> <out src.tsv>
#   python btl_text.py build <GR3.MDT> <src.tsv> <de.tsv> <out k-entries.tsv>
# Text bytes: font codes (ASCII, space 0x80, German letters 0xB8..0xBE); values below 0x20 are u16
# commands: 001F line break, 001A page end, 0016 <u16 n> name placeholder <n>, 0000 end.
# Readable form: \n line break, <n> placeholder, {xx} other bytes.
import re, struct, sys
sys.path.insert(0, __file__.rsplit('\\', 1)[0] if '\\' in __file__ else '.')
from make_lang import font_widths

REGIONS = [  # (name, start, end, kind): strings ending in 0000 / text runs inside a script
    ('call', 0x246F0, 0x27710, 'str'),
    ('advice', 0x27710, 0x27A60, 'str'),
    ('tutorial', 0x2B400, 0x2CC00, 'script'),
]
from letters import CODE as DE, normalize


def fnv32(b):
    h = 0x811C9DC5
    for x in b:
        h = ((h ^ x) * 0x01000193) & 0xFFFFFFFF
    return h


def readable(raw):
    s, i = '', 0
    while i < len(raw):
        x = raw[i]
        if x >= 0x20:
            s += ' ' if x == 0x80 else chr(x) if x < 0x7F else '{%02x}' % x
            i += 1
            continue
        t = raw[i] | raw[i + 1] << 8
        if t == 0x1F:
            s += '\\n'
            i += 2
        elif t == 0x16:
            s += '<%d>' % (raw[i + 2] | raw[i + 3] << 8)
            i += 4
        else:
            s += '{%02x%02x}' % (raw[i], raw[i + 1])
            i += 2
    return s


def encode(s):
    out, i, s = bytearray(), 0, normalize(s)
    while i < len(s):
        ch = s[i]
        if s.startswith('\\n', i):
            out += b'\x1f\x00'
            i += 2
        elif ch == '<':
            e = s.index('>', i)
            out += b'\x16\x00' + struct.pack('<H', int(s[i + 1:e]))
            i = e + 1
        elif ch == '{':
            e = s.index('}', i)
            out += bytes.fromhex(s[i + 1:e])
            i = e + 1
        elif ch == ' ':
            out.append(0x80)
            i += 1
        elif ch in DE:
            out.append(DE[ch])
            i += 1
        else:
            assert 0x21 <= ord(ch) < 0x7F, (s, ch)
            out.append(ord(ch))
            i += 1
    return bytes(out)


def strings(d, a, e):
    """0000-terminated strings (zero padding skipped)"""
    out = []
    while a < e:
        if d[a] == 0 and d[a + 1] == 0:
            a += 2
            continue
        i = a
        while not (d[i] < 0x20 and d[i] == 0 and d[i + 1] == 0):
            if d[i] >= 0x20:
                i += 1
            else:
                i += 4 if d[i] == 0x16 and d[i + 1] == 0 else 2
        out.append((a, d[a:i]))
        a = i + 2
    return out


def script_runs(d, a, e):
    """text inside the tutorial script: runs of 2+ text bytes with a lowercase letter, joined by
    line breaks (command arguments are single bytes followed by 00)"""
    run = rb'[\x21-\xff]{2,}'  # text never holds 0x20 (space is 0x80)
    out = []
    for m in re.finditer(rb'(?:%s)(?:\x1f\x00(?:%s))*' % (run, run), d[a:e]):
        t = m.group()
        if re.search(rb'[a-z]', t) and len(t) >= 4:
            out.append((a + m.start(), t))
    return out


def width(s, wt, name_w=60):
    """pixel width of a readable line; placeholders count as name_w"""
    w, s = 0, normalize(s)
    for part in re.split(r'(<\d+>|\{[0-9a-f]+\})', s):
        if not part:
            continue
        if part.startswith('<'):
            w += name_w
        elif part.startswith('{'):
            w += 10
        else:
            for ch in part:
                c = DE.get(ch, 0x80 if ch == ' ' else ord(ch))
                w += wt[c - 0x20] if 0x20 <= c < 0x20 + len(wt) else 10
    return w


def extract(gr3, out):
    d = open(gr3, 'rb').read()
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# region\toffset\tlength\tEN (generated by btl_text.py)\n')
        n = 0
        for name, a, e, kind in REGIONS:
            items = strings(d, a, e) if kind == 'str' else script_runs(d, a, e)
            for off, raw in items:
                f.write('%s\t%x\t%d\t%s\n' % (name, off, len(raw), readable(raw)))
                n += 1
    print('%d texts -> %s' % (n, out))


def build(gr3, src, de, out):
    d = open(gr3, 'rb').read()
    wt = font_widths(gr3)
    rows = [l.rstrip('\n').split('\t') for l in open(src, encoding='utf-8') if not l.startswith('#')]
    tr = {}
    for l in open(de, encoding='utf-8'):
        if l.startswith('#') or '\t' not in l:
            continue
        k, t = l.rstrip('\n').split('\t', 1)
        tr[k] = t
    maxw = {}
    group = lambda r: 'bubble' if r in ('call', 'advice') else r  # the same speech bubbles
    for reg, off, ln, en in rows:
        for line in en.split('\\n'):
            maxw[group(reg)] = max(maxw.get(group(reg), 0), width(line, wt))
    lines, warn, missing = [], 0, 0
    for reg, off, ln, en in rows:
        key = '%s:%s' % (reg, off)
        t = tr.get(key)
        if t is None:
            missing += 1
            continue
        ln = int(ln)
        probs = []
        if sorted(re.findall(r'<\d+>', t)) != sorted(re.findall(r'<\d+>', en)):
            probs.append('placeholders differ')
        dl = t.split('\\n')
        enl = en.count('\\n') + 1
        if len(dl) > max(enl, 3):
            probs.append('%d lines > %d' % (len(dl), max(enl, 3)))
        for line in dl:
            if width(line, wt) > maxw[group(reg)]:
                probs.append('%d px > %d: %s' % (width(line, wt), maxw[group(reg)], line))
        raw = encode(t)
        if len(raw) > ln:
            probs.append('%d bytes > %d' % (len(raw), ln))
        for p in probs:
            print('%s: %s  [%s]' % (key, p, t))
            warn += 1
        if probs:
            continue
        # pad with spaces at the end of the shortest line (invisible)
        pad = ln - len(raw)
        if pad:
            parts = t.split('\\n')
            k = min(range(len(parts)), key=lambda j: width(parts[j], wt))
            parts[k] += ' ' * pad
            raw = encode('\\n'.join(parts))
        assert len(raw) == ln
        o = int(off, 16)
        lines.append('k\t%x\t%x\t%x\t{%s}' % (o, ln, fnv32(d[o:o + ln]), raw.hex()))
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# generated by btl_text.py - battle texts overwritten in place\n')
        f.write('\n'.join(lines) + '\n')
    print('%d texts -> %s (%d warnings, %d untranslated)' % (len(lines), out, warn, missing))


if __name__ == '__main__':
    if sys.argv[1] == 'extract':
        extract(sys.argv[2], sys.argv[3])
    else:
        build(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5])
