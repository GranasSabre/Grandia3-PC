# Turns "EN<TAB>German" dictionaries (one per category) into id-based translation files for make_sys.py.
#   python sys_dict.py <src.tsv> <dict.tsv> <category> <out de/*.tsv>
# Lines of dict.tsv: English text exactly as in src.tsv (readable form), TAB, German. Unknown
# English texts are reported.
import os, sys
from sys_batches import tid, rows

src, dct, cat, out = sys.argv[1:5]
d = {}
for ln in open(dct, encoding='utf-8'):
    if ln.startswith('#') or '\t' not in ln:
        continue
    en, de = ln.rstrip('\n').split('\t', 1)
    d[en] = de
known = set(r[5] for r in rows(src) if r[4] == cat)
for en in d:
    if en not in known:
        print('not in %s: %r' % (cat, en))
with open(out, 'w', encoding='utf-8', newline='\n') as fo:
    fo.write('# generated by sys_dict.py from %s (%s)\n' % (os.path.basename(dct), cat))
    for en, de in d.items():
        if en in known:
            fo.write('%s\t%s\n' % (tid(cat, en), de))
print('%d of %d %s texts' % (len([e for e in d if e in known]), len(known), cat))
