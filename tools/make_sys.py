# Builds lang/<language>_sys.tsv (system texts, see runtime/src/ee/sys_text.cpp) from the extracted
# texts and the translations.
#   python make_sys.py <src.tsv> <de dir> <out.tsv> <GR3.MDT>
# Translations: <de dir>/*.tsv with "id<TAB>German" (id from sys_batches.py); "@<kind>:<a hex>" as id
# translates one entry only. Checks per text: lines no wider (font pixels) than the widest English
# line of its category, no more lines than the English text, in-place texts within their room,
# control codes ({..}) kept.
import glob, os, re, sys
from sys_batches import tid, rows, done
from make_lang import font_widths

from letters import BASE as DE_BASE, normalize


def width(line, wt):
    w, i, line = 0, 0, normalize(line)
    while i < len(line):
        if line[i] == '{':
            e = line.index('}', i)
            w += 13 * ((e - i - 1) // 4)  # two-byte glyphs (stars etc.)
            i = e + 1
            continue
        ch = DE_BASE.get(line[i], line[i])
        if ch in '„“”':
            ch = '"'
        g = ord(ch) - 0x20 if 0x20 <= ord(ch) < 0x7F else 0
        w += wt[g * 2 + 1] + 1
        i += 1
    return w


def nbytes(text):
    """encoded length in font codes (in-place texts)"""
    n = 0
    i = 0
    while i < len(text):
        if text[i] == '{':
            e = text.index('}', i)
            n += (e - i - 1) // 2
            i = e + 1
        elif text.startswith('\\n', i):
            n += 1
            i += 2
        else:
            n += 1
            i += 1
    return n + 1


def main():
    src, de_dir, out, gr3 = sys.argv[1:5]
    wt = font_widths(gr3)
    have = done(de_dir)
    allrows = list(rows(src))
    # widest English line per category, most lines per category
    maxw = {}
    for kind, a, b, c, cat, en, jp in allrows:
        for ln in en.split('\\n'):
            maxw[cat] = max(maxw.get(cat, 0), width(ln, wt))
    lines_out, warn, missing = [], 0, 0
    for kind, a, b, c, cat, en, jp in allrows:
        de = have.get('@%s:%s' % (kind, a)) or have.get(tid(cat, en))
        if de is None:
            missing += 1
            continue
        probs = []
        if re.findall(r'\{[0-9a-f]+\}', de) != re.findall(r'\{[0-9a-f]+\}', en) and cat != 'menu':
            probs.append('codes differ')
        el, dl = en.split('\\n'), de.split('\\n')
        if len(dl) > max(len(el), 1 if cat != 'desc' else 3):
            probs.append('%d lines, English %d' % (len(dl), len(el)))
        for ln in dl:
            w = width(ln, wt)
            if w > maxw[cat]:
                probs.append('%d px > %d: %s' % (w, maxw[cat], ln))
        if kind in 'ij' and nbytes(de) > int(b, 16):
            probs.append('%d bytes, room %d' % (nbytes(de), int(b, 16)))
        if kind == 'm' and nbytes(de) - 1 > 255:
            probs.append('too long')
        for p in probs:
            print('%s %s %s: %s  [%s]' % (cat, kind, a, p, de))
            warn += 1
        lines_out.append('%s\t%s\t%s\t%s\t%s' % (kind, a, b, c, de))
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w', encoding='utf-8', newline='\n') as fo:
        fo.write('# generated by make_sys.py - kind a b c text\n')
        fo.write('\n'.join(lines_out) + '\n')
    print('%d texts -> %s (%d warnings, %d untranslated)' % (len(lines_out), out, warn, missing))


if __name__ == '__main__':
    main()
