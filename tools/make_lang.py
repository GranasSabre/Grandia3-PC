# Builds lang/<language>.tsv for the runtime text hook from the translation files.
#   python make_lang.py <us mdt dir> <translation dir> <out.tsv> [GR3.MDT for size checks]
# translation dir: *.tsv files with "key<TAB>text" lines; key = FNV-1a hash (16 hex digits) of the
# original English message bytes (see make_batches.py). Text: \n line break, {hex} control sequence.
# Checks: the control sequences must match the original's in order (added page breaks are allowed);
# with the font given, pages wider than 256 px or longer than 4 lines are reported (the English
# version stays within these limits everywhere).
import glob, os, sys
import scnr_text as S

from letters import BASE as GERMAN, normalize
MAX_W, MAX_LINES = 256, 4


def fnv(b):
    h = 0xCBF29CE484222325
    for x in b:
        h = ((h ^ x) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def controls(raw):
    """control sequences; page breaks (07 + 0E speaker) are left out: translations may add pages"""
    c = [b for kind, b in S.tokens(raw) if kind == 'c']
    return [x for i, x in enumerate(c) if x[0] != 0x07 and not (x[0] == 0x0E and i and c[i - 1][0] == 0x07)]


def encode(txt):
    """like the runtime: \\n, {hex}, space; German letters measured as their base letters"""
    out, i, txt = bytearray(), 0, normalize(txt)
    while i < len(txt):
        if txt.startswith('\\n', i):
            out.append(8); i += 2; continue
        if txt[i] == '{':
            e = txt.index('}', i)
            out += bytes.fromhex(txt[i + 1:e]); i = e + 1; continue
        ch = GERMAN.get(txt[i], txt[i])
        if ch in '„“”':
            ch = '"'
        elif ch in '–—':
            ch = '-'
        elif ch == '…':
            out += b'\x4e\x4e\x4e'; i += 1; continue
        out.append(0xA0 if ch == ' ' else (ord(ch) + 0x20 if ord(ch) < 0x80 else ord('?') + 0x20))
        i += 1
    return bytes(out)


def pages(raw, wt):
    """[(width, lines)] per page, as the runtime computes the window"""
    res, lw, w, lines = [], 0, 0, 1
    for kind, b in S.tokens(raw):
        if kind == 'c':
            if b[0] == 0x07:
                res.append((max(w, lw), lines)); lw = w = 0; lines = 1
            elif len(b) == 2 and b[1] >= 0xF0:
                lw += 13
            continue
        for x in b:
            if x == 8:
                w = max(w, lw); lw = 0; lines += 1
            elif x >= 0x40:
                lw += wt[(x - 0x40) * 2 + 1] + 1
    res.append((max(w, lw), lines))
    return res


MENUS = set()  # keys of choice menus (message opcode 0D 09): one line per option


def originals(mdt_dir):
    orig = {}
    for f in sorted(glob.glob(os.path.join(mdt_dir, '*.MDT'))):
        s = S.script(open(f, 'rb').read())
        for o, raw in S.texts(s, False):
            k = fnv(raw)
            orig.setdefault(k, raw)
            if o >= 15 and s[o - 15] == 0x0D and s[o - 14] == 0x09:
                MENUS.add(k)
    return orig


def check(key, txt, orig, wt):
    """list of problems of one translation"""
    raw = orig.get(key)
    if raw is None:
        return ['unknown key']
    enc = encode(txt)
    probs = []
    bad = sorted({c for c in normalize(txt) if ord(c) > 126 and c not in GERMAN and c not in '„“”–—…'})
    if bad:
        probs.append('characters missing in the font: %s' % ' '.join(bad))
    if controls(enc) != controls(raw):
        probs.append('control sequences %s, original %s' % (' '.join(c.hex() for c in controls(enc)), ' '.join(c.hex() for c in controls(raw))))
    if key in MENUS and enc.count(8) != raw.count(8):
        probs.append('choice menu: %d options, original %d' % (enc.count(8) + 1, raw.count(8) + 1))
    if wt:
        for n, (w, l) in enumerate(pages(enc, wt)):
            if w > MAX_W or l > MAX_LINES:
                probs.append('page %d: %d px, %d lines' % (n + 1, w, l))
    return probs


def font_widths(gr3):
    d = open(gr3, 'rb').read()
    return d[0x34700 + 0x1A0:0x34700 + 0x520]


if __name__ == '__main__':
    mdt_dir, tr_dir, out = sys.argv[1], sys.argv[2], sys.argv[3]
    wt = font_widths(sys.argv[4]) if len(sys.argv) > 4 else None
    orig = originals(mdt_dir)
    lines = ['# generated by make_lang.py - key<TAB>text']
    seen = {}
    warn = 0
    for tf in sorted(glob.glob(os.path.join(tr_dir, '*.tsv'))):
        for n, ln in enumerate(open(tf, encoding='utf-8'), 1):
            ln = ln.rstrip('\n')
            if not ln or ln.startswith('#'):
                continue
            if len(ln) < 18 or ln[16] != '\t':
                print('%s:%d: bad line' % (os.path.basename(tf), n)); warn += 1
                continue
            key, txt = int(ln[:16], 16), ln[17:]
            for p in check(key, txt, orig, wt):
                print('%s:%d %016x: %s' % (os.path.basename(tf), n, key, p)); warn += 1
            seen[key] = txt
    for key, txt in seen.items():
        lines.append('%016x\t%s' % (key, txt))
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('%d texts -> %s (%d warnings, %d of %d distinct messages translated)' % (len(seen), out, warn, len(seen), len(orig)))
